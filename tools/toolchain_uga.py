Vec3 = tuple[float, float, float]
Tri = tuple[int, int, int]


def v_sub(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def v_add(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def v_cross(a: Vec3, b: Vec3) -> Vec3:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def v_dot(a: Vec3, b: Vec3) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def v_norm(a: Vec3) -> Vec3:
    mag = math.sqrt(v_dot(a, a))
    if mag < 1e-12:
        return (0.0, 0.0, 1.0)
    return (a[0] / mag, a[1] / mag, a[2] / mag)


def compute_vertex_normals(vertices: list[Vec3], triangles: list[Tri]) -> list[Vec3]:
    """Compute area-weighted unit outward vertex normals from CCW triangles."""
    nv = len(vertices)
    acc = [[0.0, 0.0, 0.0] for _ in range(nv)]
    for i0, i1, i2 in triangles:
        if not (0 <= i0 < nv and 0 <= i1 < nv and 0 <= i2 < nv):
            continue
        p0, p1, p2 = vertices[i0], vertices[i1], vertices[i2]
        n = v_cross(v_sub(p1, p0), v_sub(p2, p0))
        for idx in (i0, i1, i2):
            acc[idx][0] += n[0]
            acc[idx][1] += n[1]
            acc[idx][2] += n[2]
    return [v_norm((a[0], a[1], a[2])) for a in acc]


def signed_mesh_volume(vertices: list[Vec3], triangles: list[Tri]) -> float:
    """Divergence-theorem signed volume: V = (1/6) sum_{f} v0 . (v1 x v2)."""
    total = 0.0
    for i0, i1, i2 in triangles:
        p0, p1, p2 = vertices[i0], vertices[i1], vertices[i2]
        total += v_dot(p0, v_cross(p1, p2))
    return total / 6.0


def mesh_bounding_box(vertices: list[Vec3]) -> tuple[Vec3, Vec3]:
    xs = [p[0] for p in vertices]
    ys = [p[1] for p in vertices]
    zs = [p[2] for p in vertices]
    return (min(xs), min(ys), min(zs)), (max(xs), max(ys), max(zs))


def check_manifold_topology(vertices: list[Vec3], triangles: list[Tri]) -> dict[str, Any]:
    """Verify 2-manifold edge pairing: every half-edge (u, v) appears once and (v, u) exists."""
    half_edges: dict[tuple[int, int], int] = {}
    degenerate_faces = 0
    for i0, i1, i2 in triangles:
        if i0 == i1 or i1 == i2 or i2 == i0:
            degenerate_faces += 1
        for u, v in ((i0, i1), (i1, i2), (i2, i0)):
            half_edges[(u, v)] = half_edges.get((u, v), 0) + 1

    duplicate_half_edges = sum(1 for c in half_edges.values() if c > 1)
    unpaired_half_edges = sum(1 for (u, v) in half_edges if (v, u) not in half_edges)
    undirected_edges = { (min(u, v), max(u, v)) for (u, v) in half_edges }
    v_count = len(vertices)
    e_count = len(undirected_edges)
    f_count = len(triangles)
    euler_chi = v_count - e_count + f_count
    is_watertight = (
        degenerate_faces == 0
        and duplicate_half_edges == 0
        and unpaired_half_edges == 0
        and 3 * f_count == 2 * e_count
    )
    return {
        "is_watertight": is_watertight,
        "vertices": v_count,
        "edges": e_count,
        "faces": f_count,
        "euler_characteristic": euler_chi,
        "degenerate_faces": degenerate_faces,
        "duplicate_half_edges": duplicate_half_edges,
        "unpaired_half_edges": unpaired_half_edges,
    }


def add_hexahedron(
    vertices: list[Vec3],
    colors: list[Vec3],
    triangles: list[Tri],
    corners8: list[Vec3],
    color: Vec3,
) -> None:
    """Append a closed 8-vertex, 12-triangle hexahedron with outward CCW winding.

    corners8 order:
      bottom z-face: 0:(x0,y0,z0), 1:(x1,y0,z0), 2:(x1,y1,z0), 3:(x0,y1,z0)
      top    z-face: 4:(x0,y0,z1), 5:(x1,y0,z1), 6:(x1,y1,z1), 7:(x0,y1,z1)
    """
    base = len(vertices)
    for pt in corners8:
        vertices.append(pt)
        colors.append(color)
    local_tris = [
        # Bottom (-Z): outward normal -Z -> (0, 3, 2), (0, 2, 1)
        (0, 3, 2), (0, 2, 1),
        # Top (+Z): outward normal +Z -> (4, 5, 6), (4, 6, 7)
        (4, 5, 6), (4, 6, 7),
        # Front (-Y): (0, 1, 5), (0, 5, 4)
        (0, 1, 5), (0, 5, 4),
        # Right (+X): (1, 2, 6), (1, 6, 5)
        (1, 2, 6), (1, 6, 5),
        # Back (+Y): (2, 3, 7), (2, 7, 6)
        (2, 3, 7), (2, 7, 6),
        # Left (-X): (3, 0, 4), (3, 4, 7)
        (3, 0, 4), (3, 4, 7),
    ]
    for a, b, c in local_tris:
        triangles.append((base + a, base + b, base + c))


def add_box(
    vertices: list[Vec3],
    colors: list[Vec3],
    triangles: list[Tri],
    x0: float, y0: float, z0: float,
    x1: float, y1: float, z1: float,
    color: Vec3,
) -> None:
    corners = [
        (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
        (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),
    ]
    add_hexahedron(vertices, colors, triangles, corners, color)


