def generate_folio_assets(
    slug: str,
    folio_id: str,
    title: str,
    script_path: Path,
    files_dir: Path,
    formats: tuple[str, ...] = ("glb", "step", "3mf"),
) -> dict[str, Any]:
    """Generate deterministic 3D files and manifest.json for a Toolbox Folio (x01..x06)."""
    geom = BUILDERS[slug]()
    script_sha256 = hashlib.sha256(script_path.read_bytes()).hexdigest()
    provenance = {
        "folio_id": folio_id,
        "slug": slug,
        "title": title,
        "generator_script": f"skills/toolchain/{slug}/{script_path.name}",
        "generator_script_sha256": script_sha256,
        "parameters": geom["parameters"],
        "tool_versions": {"python": "3.x-stdlib", "uga_kernel": "1.0.0"},
        "license": "CC0-1.0 / CC-BY-4.0",
        "boundary": BOUNDARY_EN,
    }

    files_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{slug}_artifact"
    generated_files: list[dict[str, Any]] = []

    if "glb" in formats:
        p_glb = files_dir / f"{stem}.glb"
        raw = write_glb(p_glb, geom["vertices"], geom["triangles"], geom["colors"], provenance)
        generated_files.append({
            "filename": p_glb.name,
            "format": "GLB (glTF 2.0 Binary)",
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })

    if "step" in formats:
        p_step = files_dir / f"{stem}.step"
        raw = write_step_ap242(p_step, geom["vertices"], geom["triangles"], stem.upper(), provenance)
        generated_files.append({
            "filename": p_step.name,
            "format": "STEP AP242 (ISO 10303-242)",
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })

    if "3mf" in formats:
        p_3mf = files_dir / f"{stem}.3mf"
        raw = write_3mf(p_3mf, geom["vertices"], geom["triangles"], title, provenance)
        generated_files.append({
            "filename": p_3mf.name,
            "format": "3MF Core 1.2.3",
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })

    if "dxf" in formats and "dxf_segments" in geom:
        p_dxf = files_dir / f"{stem}.dxf"
        raw = write_dxf(p_dxf, geom["dxf_segments"], provenance)
        generated_files.append({
            "filename": p_dxf.name,
            "format": "DXF (AutoCAD ASCII R2000)",
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })

    fuzz_cases = []
    if slug == "x01":
        fuzz_cases = write_x01_fuzz_fixtures(files_dir)

    topo = check_manifold_topology(geom["vertices"], geom["triangles"])
    vol = signed_mesh_volume(geom["vertices"], geom["triangles"])
    bmin, bmax = mesh_bounding_box(geom["vertices"])

    manifest = {
        "schema_version": "1.0.0",
        "folio_id": folio_id,
        "slug": slug,
        "title": title,
        "generator_script": provenance["generator_script"],
        "generator_script_sha256": script_sha256,
        "parameters": geom["parameters"],
        "tool_versions": provenance["tool_versions"],
        "license": provenance["license"],
        "boundary_en": BOUNDARY_EN,
        "boundary_es": BOUNDARY_ES,
        "expected_geometry": {
            "analytical_volume": round(geom["analytical_volume"], 4),
            "signed_mesh_volume": round(vol, 4),
            "euler_characteristic": geom["expected_euler_chi"],
            "vertices": topo["vertices"],
            "edges": topo["edges"],
            "faces": topo["faces"],
            "bbox_min": list(bmin_bmax_round(bmin, bmax)[0]),
            "bbox_max": list(bmin_bmax_round(bmin, bmax)[1]),
        },
        "files": generated_files,
        "fuzz_fixtures": fuzz_cases,
    }
    manifest_path = files_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest


# ---------------------------------------------------------------------------
# Deterministic Byte-Level Verifier + Planted-Defect Knockout Engine
# ---------------------------------------------------------------------------

def verify_folio_assets(
    slug: str,
    files_dir: Path,
    script_path: Path,
    planted_defect_only: bool = False,
) -> dict[str, Any]:
    """Run the byte-level verifier on committed files, then verify planted-defect knockout fails."""
    manifest_path = files_dir / "manifest.json"
    if not manifest_path.is_file():
        raise AssertionError(f"Missing manifest.json in {files_dir}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    # 1. Verify generator script SHA-256 matches manifest
    actual_script_sha = hashlib.sha256(script_path.read_bytes()).hexdigest()
    if actual_script_sha != manifest["generator_script_sha256"]:
        raise AssertionError(
            f"Generator script SHA-256 mismatch for {slug}: "
            f"manifest={manifest['generator_script_sha256']} vs actual={actual_script_sha}"
        )

    # 2. Verify every committed file exists and matches its SHA-256 and byte length
    for f_entry in manifest["files"]:
        fp = files_dir / f_entry["filename"]
        if not fp.is_file():
            raise AssertionError(f"Missing committed artifact file: {fp}")
        raw = fp.read_bytes()
        if len(raw) != f_entry["bytes"]:
            raise AssertionError(f"Byte size mismatch on {fp.name}: {len(raw)} != {f_entry['bytes']}")
        sha = hashlib.sha256(raw).hexdigest()
        if sha != f_entry["sha256"]:
            raise AssertionError(f"SHA-256 mismatch on {fp.name}: {sha} != {f_entry['sha256']}")

        # Format-specific structural checks
        if fp.suffix == ".step":
            txt = raw.decode("utf-8")
            assert txt.startswith("ISO-10303-21;"), f"{fp.name} missing ISO-10303-21 header"
            assert "AP242_MANAGED_MODEL_BASED_3D_ENGINEERING_MIM_LF" in txt, f"{fp.name} missing AP242 schema"
            assert "MANIFOLD_SOLID_BREP" in txt and "CLOSED_SHELL" in txt, f"{fp.name} missing B-rep shell"
        elif fp.suffix == ".3mf":
            with zipfile.ZipFile(io.BytesIO(raw), "r") as zf:
                names = set(zf.namelist())
                assert "3D/3dmodel.model" in names, f"{fp.name} missing 3D/3dmodel.model"
                model_xml = zf.read("3D/3dmodel.model").decode("utf-8")
                assert "<mesh>" in model_xml and "<triangles>" in model_xml, f"{fp.name} missing mesh XML"
        elif fp.suffix == ".dxf":
            txt = raw.decode("utf-8")
            assert "SECTION" in txt and "ENTITIES" in txt and "EOF" in txt, f"{fp.name} invalid DXF structure"
            assert "MOUNTAIN" in txt and "CUT" in txt, f"{fp.name} missing crease/cut layers"

    # 3. Parse GLB and verify manifoldness, signed volume, Euler characteristic, and bounding box
    glb_path = files_dir / f"{slug}_artifact.glb"
    glb_data = glb_path.read_bytes()
    parsed = parse_glb(glb_data)
    vertices = parsed["vertices"]
    triangles = parsed["triangles"]

    topo = check_manifold_topology(vertices, triangles)
    if not topo["is_watertight"]:
        raise AssertionError(f"{slug} GLB failed manifold watertightness check: {topo}")

    exp = manifest["expected_geometry"]
    if topo["euler_characteristic"] != exp["euler_characteristic"]:
        raise AssertionError(
            f"{slug} Euler characteristic {topo['euler_characteristic']} != expected {exp['euler_characteristic']}"
        )

    vol = signed_mesh_volume(vertices, triangles)
    rel_vol_err = abs(vol - exp["analytical_volume"]) / max(abs(exp["analytical_volume"]), 1e-9)
    if rel_vol_err > 1e-4:
        raise AssertionError(
            f"{slug} signed volume {vol:.4f} differs from analytical {exp['analytical_volume']:.4f} "
            f"(rel_err={rel_vol_err:.6e})"
        )

    bmin, bmax = bmin_bmax_round(*mesh_bounding_box(vertices))
    for i in range(3):
        if abs(bmin[i] - exp["bbox_min"][i]) > 1e-2 or abs(bmax[i] - exp["bbox_max"][i]) > 1e-2:
            raise AssertionError(f"{slug} bounding box {[bmin, bmax]} != expected {[exp['bbox_min'], exp['bbox_max']]}")

    # 4. If X.01, verify all 4 malformed fuzz GLB fixtures are rejected
    fuzz_rejected = 0
    for fz in manifest.get("fuzz_fixtures", []):
        fz_path = files_dir / fz["file"]
        fz_bytes = fz_path.read_bytes()
        rejected = False
        try:
            p_fz = parse_glb(fz_bytes)
            t_fz = check_manifold_topology(p_fz["vertices"], p_fz["triangles"])
            v_fz = signed_mesh_volume(p_fz["vertices"], p_fz["triangles"])
            if not t_fz["is_watertight"] or abs(v_fz - exp["analytical_volume"]) > 1.0:
                rejected = True
        except ValueError:
            rejected = True
        if not rejected:
            raise AssertionError(f"Fuzz fixture {fz['file']} was NOT rejected by verifier!")
        fuzz_rejected += 1

    # 5. Planted-Defect Knockout Test (mandatory on every X verifier!)
    # Mutate triangle 0 by flipping its winding (i0, i1, i2) -> (i0, i2, i1) and corrupting vertex 0 Z-coordinate
    mutated_tris = list(triangles)
    i0, i1, i2 = mutated_tris[0]
    mutated_tris[0] = (i0, i2, i1)
    mutated_topo = check_manifold_topology(vertices, mutated_tris)
    mutated_vol = signed_mesh_volume(vertices, mutated_tris)

    if planted_defect_only:
        # When invoked with --planted-defect, run the valid assertions against the mutated geometry so it FAILS
        if not mutated_topo["is_watertight"] or abs(mutated_vol - exp["analytical_volume"]) > 1e-2:
            raise AssertionError(
                f"PLANTED_DEFECT_CAUGHT: Flipped triangle 0 normal broke watertightness "
                f"(duplicate_half_edges={mutated_topo['duplicate_half_edges']}, "
                f"unpaired_half_edges={mutated_topo['unpaired_half_edges']}, "
                f"signed_volume={mutated_vol:.2f} vs analytical={exp['analytical_volume']:.2f})"
            )

    if mutated_topo["is_watertight"]:
        raise AssertionError(f"Planted-defect knockout failed to break manifoldness on {slug}!")

    return {
        "status": "PASS",
        "folio_id": manifest["folio_id"],
        "slug": slug,
        "title": manifest["title"],
        "url": f"https://informatico.ai/toolchain/{slug}/",
        "boundary": BOUNDARY_EN,
        "geometry_checks": {
            "watertight_2_manifold": topo["is_watertight"],
            "vertices": topo["vertices"],
            "edges": topo["edges"],
            "faces": topo["faces"],
            "euler_characteristic": topo["euler_characteristic"],
            "signed_volume_mm3": round(vol, 3),
            "analytical_volume_mm3": round(exp["analytical_volume"], 3),
            "relative_volume_error": round(rel_vol_err, 8),
            "planted_defect_knockout": "REJECTED_AS_EXPECTED",
            "fuzz_fixtures_rejected": fuzz_rejected,
        },
        "verified_files": [f["filename"] for f in manifest["files"]],
    }
